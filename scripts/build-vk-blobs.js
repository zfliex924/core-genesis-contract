#!/usr/bin/env node
/* eslint-disable no-console */
//
// Extract the verifying-key constants from each MASP snarkjs verifier and emit
// the precompile-format VK blob (alpha || beta || gamma || delta || IC[0..n]).
//
// The blob layout matches zsp-chain's groth16Verify precompile (0x6a):
//   alpha   (G1, 64B)
//   beta    (G2, 128B; x_im || x_re || y_im || y_re)
//   gamma   (G2, 128B)
//   delta   (G2, 128B)
//   IC[i]   (G1, 64B each), i = 0..n
//
// Run: node scripts/build-vk-blobs.js
// Output is appended to stdout — copy/paste into MASPGrothPrecompileVerifier.sol.

const fs = require('fs');
const path = require('path');

const verifiers = [
  { name: 'Deposit',        n: 3, file: 'external/masp/src/verifiers/DepositGroth16Verifier.sol' },
  { name: 'Transaction',    n: 9, file: 'external/masp/src/verifiers/TransactionGroth16Verifier.sol' },
  { name: 'Transaction1x2', n: 8, file: 'external/masp/src/verifiers/Transaction1x2Groth16Verifier.sol' },
];

function toHex32(decStr) {
  let h = BigInt(decStr).toString(16);
  if (h.length > 64) throw new Error(`scalar overflow: ${decStr}`);
  return h.padStart(64, '0');
}

function extract(file, name, n) {
  const src = fs.readFileSync(file, 'utf8');
  const grab = (key) => {
    const m = src.match(new RegExp(`uint256 constant\\s+${key}\\s*=\\s*(\\d+)\\s*;`));
    if (!m) throw new Error(`${file}: missing constant ${key}`);
    return m[1];
  };
  const parts = [];
  // alpha (G1)
  parts.push(toHex32(grab('alphax')), toHex32(grab('alphay')));
  // beta (G2)
  parts.push(toHex32(grab('betax1')), toHex32(grab('betax2')),
             toHex32(grab('betay1')), toHex32(grab('betay2')));
  // gamma (G2)
  parts.push(toHex32(grab('gammax1')), toHex32(grab('gammax2')),
             toHex32(grab('gammay1')), toHex32(grab('gammay2')));
  // delta (G2)
  parts.push(toHex32(grab('deltax1')), toHex32(grab('deltax2')),
             toHex32(grab('deltay1')), toHex32(grab('deltay2')));
  // IC (n+1 G1 points)
  for (let i = 0; i <= n; i++) {
    parts.push(toHex32(grab(`IC${i}x`)), toHex32(grab(`IC${i}y`)));
  }
  return parts.join('');
}

const root = path.resolve(__dirname, '..');
console.log('// Auto-generated by scripts/build-vk-blobs.js');
console.log('// Layout: alpha(G1,64B) || beta(G2,128B) || gamma(G2,128B) || delta(G2,128B) || IC[0..n](G1,64B each)');
console.log('');
for (const v of verifiers) {
  const blob = extract(path.join(root, v.file), v.name, v.n);
  const expectedLen = (64 + 128 + 128 + 128 + (v.n + 1) * 64) * 2; // hex chars
  if (blob.length !== expectedLen) {
    throw new Error(`${v.name}: blob length ${blob.length} != expected ${expectedLen}`);
  }
  console.log(`// ${v.name}: numPubInputs=${v.n}, IC count=${v.n + 1}, blob = ${blob.length / 2} bytes`);
  // Wrap to 64 hex chars per line for readability
  const wrapped = blob.match(/.{1,64}/g).map(line => `        hex"${line}"`).join('\n');
  console.log(`bytes constant ${v.name.toUpperCase()}_VK_BLOB = (\n${wrapped}\n    );\n`);
}
